'use strict';
const assert = require('assert');
const E = require('../dev/automation/contentEngine');
const body = 'احتفظ بنسخة ورقية من عبارة الاسترداد في مكان آمن بعيد عن هاتفك حتى لا تفقد الوصول إلى المحفظة عند تلف الجهاز.';
assert.strictEqual(E.assembleTweet('نص قصير', ''), null, 'decoration cannot make a fragment into a complete body');
assert.strictEqual(E.validateTweet('تام تام في سوق الكريبتو قبل الدخول في الصفقة.', '').valid, false, 'adjacent duplicate words must be rejected');
assert.strictEqual(E.assembleTweet(body, '', { decorate: false }).text, body, 'custom prompt body must not gain unsolicited hashtags');
assert.strictEqual(E.validateTweet('احفظ العبارة في مكان آمن (بعيدا عن الهاتف.', '').valid, false, 'unclosed parentheses indicate an incomplete item');
assert.strictEqual(E.validateTweet(body, '').valid, true);
assert.ok(E.buildSessionSystem({}).includes('190-225'), 'default length target belongs to the static system block too');
const custom = 'اكتب العربية دون إيموجي أو هاشتاق، بطول موجز.';
assert.strictEqual(E.buildSessionSystem({ customSystem: custom }), custom);
const round = E.buildRoundUser({ quantity: 3, customSystem: custom, styles: ['أسلوب معاكس للتعليمات'] });
assert.ok(!/190-225|إيموجي|هاشتاق|أسلوب معاكس/.test(round), 'technical round constraints must not override custom tone/length/style');
const nearLimit = 'هذه ملاحظة كاملة تشرح حماية المحفظة الرقمية دون إضافة أي صياغة خارج النص. ' + 'أ'.repeat(190) + '.';
const assembled = E.assembleTweet(nearLimit, '');
assert.ok(assembled && E.validateTweet(assembled.text, '').valid, 'optional decoration must not push an otherwise valid body over 280');
assert.ok(assembled.text.startsWith(nearLimit), 'never silently cut or rewrite a body to fit');
console.log('✅ quality boundary rejects fragments/repeated words and preserves complete custom bodies');
